#!/usr/bin/env bash
#
# scripts/test-secret-hooks.sh — proves the gitleaks gate end to end.
#
# Installs the REAL .husky/pre-commit + .husky/pre-push, scripts/secret-scan.sh
# and .gitleaks.toml from this checkout into throwaway repos wired exactly like
# production (core.hooksPath → .husky/_ with husky's runner), then drives git
# through them. Every case can fail. Cases:
#   (a) planted credential BLOCKED at pre-commit, before lint-staged ran
#   (b) same credential BLOCKED at pre-push — new branch, and existing-branch range
#   (c) clean commit and clean push PASS (and lint-staged did run after the scan)
#   (d) missing gitleaks binary BLOCKS commit and push
#   (e) SECRETS_SCAN_SKIP=1 PASSES with a loud warning (commit and push)
#   (f) deleting a remote branch PASSES even though the local branch is dirty
#   (g) missing .gitleaks.toml BLOCKS;  (h) corrupt .gitleaks.toml BLOCKS as a scanner error
#   (i) a worktree WITHOUT scripts/secret-scan.sh or .gitleaks.toml is still gated
#       through the hook owner's copies (the global core.hooksPath layout)
#   (j) no output ever contains the planted credential
#
# The fake credential is assembled at runtime from fragments, so neither this
# file nor any fixture holds a scannable literal. It is a GitHub-PAT-shaped
# string, a rule gitleaks' built-in set catches and .gitleaks.toml does not
# allowlist at the repo root (verified: probe 2026-10-22; AWS's documented
# example key is allowlisted by gitleaks itself, which is why it is not used).
#
# Run: bash scripts/test-secret-hooks.sh     (npm run test:secret-hooks /
#      pytest tests/scripts/test_secret_hooks.py wrap it)

set -u

SRC="$(cd "$(dirname "$0")/.." && pwd)"
if ! command -v gitleaks > /dev/null 2>&1; then
  echo "test-secret-hooks: gitleaks is not installed (brew install gitleaks) — cannot run" >&2
  exit 1
fi

TMP="$(mktemp -d "${TMPDIR:-/tmp}/secret-hooks-test.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
PASS=0
FAIL=0
ok() {
  PASS=$((PASS + 1))
  echo "PASS $1"
}
bad() {
  FAIL=$((FAIL + 1))
  echo "FAIL $1"
  [ -n "${2:-}" ] && [ -f "$2" ] && sed 's/^/     | /' "$2" | tail -25
}

PLANTED="$(printf '%s%s%s%s%s' 'ghp_' 'Zq7Xw2Kp9R' 't4Vb6Nm1Lc' '8Hj3Fd5Gs0' 'TyUe2W')"
[ ${#PLANTED} -eq 40 ] || {
  echo "planted credential malformed (${#PLANTED} chars)"
  exit 1
}
ALL_OUT="$TMP/all-output.txt" # every hook transcript is appended here for (j)

# lint-staged stand-in: records that it ran, so (a) can prove the scan came first
BIN="$TMP/bin"
mkdir -p "$BIN"
cat > "$BIN/npx" << 'EOF'
#!/bin/sh
[ -n "${NPX_SENTINEL:-}" ] && : > "$NPX_SENTINEL"
exit 0
EOF
chmod +x "$BIN/npx"
export PATH="$BIN:$PATH"
# PATH for (d): git and the POSIX tools only — no /opt/homebrew/bin, so no gitleaks
NOBIN="$TMP/nobin"
mkdir -p "$NOBIN"
ln -s "$(command -v git)" "$NOBIN/git"
NO_GITLEAKS_PATH="$NOBIN:/usr/bin:/bin"
NOHOOKS="$TMP/nohooks"
mkdir -p "$NOHOOKS"

# husky v9 runner (.husky/_/h is gitignored, generated by `npm ci`); this is
# the part of it that matters: resolve .husky/<hook> and run it with sh -e.
write_runner() { # $1 = .husky dir
  mkdir -p "$1/_"
  cat > "$1/_/h" << 'EOF'
#!/usr/bin/env sh
n=$(basename "$0")
s=$(dirname "$(dirname "$0")")/$n
[ ! -f "$s" ] && exit 0
export PATH="node_modules/.bin:$PATH"
sh -e "$s" "$@"
c=$?
[ $c != 0 ] && echo "husky - $n script failed (code $c)"
exit $c
EOF
  for h in pre-commit pre-push; do
    printf '#!/usr/bin/env sh\n. "$(dirname "$0")/h"\n' > "$1/_/$h"
    chmod +x "$1/_/$h"
  done
}

install_gate() { # $1 = dir that receives .husky/, scripts/secret-scan.sh, .gitleaks.toml
  mkdir -p "$1/.husky" "$1/scripts"
  cp "$SRC/.husky/pre-commit" "$SRC/.husky/pre-push" "$1/.husky/"
  cp "$SRC/scripts/secret-scan.sh" "$1/scripts/"
  cp "$SRC/.gitleaks.toml" "$1/"
  write_runner "$1/.husky"
}

make_repo() { # $1 = repo dir, $2 = hooks owner dir (default: the repo itself)
  local r="$1" owner="${2:-$1}"
  git init -q "$r"
  git -C "$r" symbolic-ref HEAD refs/heads/main
  git -C "$r" config user.name t
  git -C "$r" config user.email t@t
  [ "$owner" = "$r" ] && install_gate "$r"
  git -C "$r" config core.hooksPath "$owner/.husky/_"
  printf 'seed\n' > "$r/README"
  git -C "$r" add -A
  git -C "$r" -c core.hooksPath="$NOHOOKS" commit -q -m seed
  git init -q --bare "$r.remote"
  git -C "$r" remote add origin "$r.remote"
}

plant() {
  printf 'token=%s\n' "$PLANTED" > "$1/leak.txt"
  git -C "$1" add leak.txt
}
clean_file() {
  printf 'hello %s\n' "$2" > "$1/$2.txt"
  git -C "$1" add "$2.txt"
}
# run <outfile> <cmd…>  — captures the transcript, returns the command's rc
run() {
  local out="$1"
  shift
  "$@" > "$out" 2>&1
  local rc=$?
  cat "$out" >> "$ALL_OUT"
  return $rc
}

# ── (a) pre-commit blocks, before lint-staged ─────────────────────────────────
r="$TMP/a"
make_repo "$r"
plant "$r"
if run "$TMP/a.out" env NPX_SENTINEL="$TMP/a.npx" git -C "$r" commit -q -m leak; then
  bad "(a) planted credential was COMMITTED" "$TMP/a.out"
elif ! grep -q 'github-pat' "$TMP/a.out"; then
  bad "(a) commit blocked but not by the gitleaks finding" "$TMP/a.out"
elif [ -e "$TMP/a.npx" ]; then
  bad "(a) lint-staged ran before the secrets gate" "$TMP/a.out"
else
  ok "(a) pre-commit blocked the planted credential before lint-staged (rule github-pat)"
fi

# ── (c) clean commit passes and lint-staged ran after the gate ────────────────
git -C "$r" reset -q leak.txt && rm -f "$r/leak.txt"
clean_file "$r" ok
if run "$TMP/c.out" env NPX_SENTINEL="$TMP/c.npx" git -C "$r" commit -q -m clean \
  && [ -e "$TMP/c.npx" ] && grep -q 'staged content clean' "$TMP/c.out"; then
  ok "(c) clean commit passed; lint-staged ran after the gate"
else
  bad "(c) clean commit failed or lint-staged did not run" "$TMP/c.out"
fi
if run "$TMP/c2.out" git -C "$r" push -q origin main && grep -q '1 ref(s) clean' "$TMP/c2.out"; then
  ok "(c) clean push passed (new branch scanned: 1 ref)"
else
  bad "(c) clean push failed" "$TMP/c2.out"
fi

# ── (e) bypass at commit, (b) new-branch push blocked ─────────────────────────
r="$TMP/b"
make_repo "$r"
plant "$r"
if run "$TMP/e1.out" env SECRETS_SCAN_SKIP=1 git -C "$r" commit -q -m leak \
  && grep -q 'SECRETS_SCAN_SKIP=1' "$TMP/e1.out" && grep -q 'BYPASSED' "$TMP/e1.out"; then
  ok "(e) SECRETS_SCAN_SKIP=1 let the commit through with a loud warning"
else
  bad "(e) bypassed commit failed or warned silently" "$TMP/e1.out"
fi
if run "$TMP/b1.out" git -C "$r" push -q origin main; then
  bad "(b) new-branch push with a planted credential was ACCEPTED" "$TMP/b1.out"
elif grep -q 'github-pat' "$TMP/b1.out" && grep -q 'new branch' "$TMP/b1.out"; then
  ok "(b) pre-push blocked the new branch (commits not on any remote)"
else
  bad "(b) new-branch push blocked for the wrong reason" "$TMP/b1.out"
fi
if run "$TMP/e2.out" env SECRETS_SCAN_SKIP=1 git -C "$r" push -q origin main \
  && grep -q 'BYPASSED' "$TMP/e2.out"; then
  ok "(e) SECRETS_SCAN_SKIP=1 let the push through with a loud warning"
else
  bad "(e) bypassed push failed or warned silently" "$TMP/e2.out"
fi

# ── (b) existing-branch range blocked, (f) deletion passes ────────────────────
r="$TMP/f"
make_repo "$r"
clean_file "$r" one
run "$TMP/f0.out" git -C "$r" commit -q -m one && run "$TMP/f1.out" git -C "$r" push -q origin main \
  || bad "(b/f) setup: clean first push failed" "$TMP/f1.out"
git -C "$r" checkout -q -b feat
clean_file "$r" two
run "$TMP/f2.out" git -C "$r" commit -q -m two && run "$TMP/f3.out" git -C "$r" push -q origin feat \
  || bad "(b/f) setup: clean feat push failed" "$TMP/f3.out"
plant "$r"
run "$TMP/f4.out" env SECRETS_SCAN_SKIP=1 git -C "$r" commit -q -m leak || bad "(b/f) setup: bypass commit failed" "$TMP/f4.out"
if run "$TMP/b2.out" git -C "$r" push -q origin feat; then
  bad "(b) existing-branch push with a planted credential was ACCEPTED" "$TMP/b2.out"
elif grep -q 'github-pat' "$TMP/b2.out" && grep -Eq 'refs/heads/feat [0-9a-f]{7}\.\.[0-9a-f]{7}' "$TMP/b2.out"; then
  ok "(b) pre-push blocked the existing-branch range <remote>..<local>"
else
  bad "(b) existing-branch push blocked for the wrong reason" "$TMP/b2.out"
fi
if run "$TMP/f5.out" git -C "$r" push -q origin :feat && grep -q '(deletion)' "$TMP/f5.out"; then
  ok "(f) deleting remote feat passed (ref skipped) although local feat carries the credential"
else
  bad "(f) deletion push failed" "$TMP/f5.out"
fi

# ── (d) missing gitleaks blocks commit and push ───────────────────────────────
r="$TMP/d"
make_repo "$r"
clean_file "$r" ok
if run "$TMP/d1.out" env PATH="$NO_GITLEAKS_PATH" git -C "$r" commit -q -m clean; then
  bad "(d) commit PASSED with no gitleaks on PATH (fail-open)" "$TMP/d1.out"
elif grep -q 'gitleaks is not installed' "$TMP/d1.out" && grep -q 'brew install gitleaks' "$TMP/d1.out"; then
  ok "(d) missing gitleaks blocked the commit with install instructions"
else
  bad "(d) commit blocked for the wrong reason" "$TMP/d1.out"
fi
run "$TMP/d2.out" git -C "$r" commit -q -m clean || bad "(d) setup: clean commit with gitleaks present failed" "$TMP/d2.out"
if run "$TMP/d3.out" env PATH="$NO_GITLEAKS_PATH" git -C "$r" push -q origin main; then
  bad "(d) push PASSED with no gitleaks on PATH (fail-open)" "$TMP/d3.out"
elif grep -q 'gitleaks is not installed' "$TMP/d3.out"; then
  ok "(d) missing gitleaks blocked the push"
else
  bad "(d) push blocked for the wrong reason" "$TMP/d3.out"
fi

# ── (g) missing config blocks, (h) corrupt config is a scanner error ──────────
r="$TMP/g"
make_repo "$r"
clean_file "$r" ok
rm -f "$r/.gitleaks.toml"
if run "$TMP/g.out" git -C "$r" commit -q -m clean; then
  bad "(g) commit PASSED without .gitleaks.toml (fail-open)" "$TMP/g.out"
elif grep -q '.gitleaks.toml not found' "$TMP/g.out"; then
  ok "(g) missing .gitleaks.toml blocked the commit"
else
  bad "(g) commit blocked for the wrong reason" "$TMP/g.out"
fi
printf 'title = [\n' > "$r/.gitleaks.toml"
if run "$TMP/h.out" git -C "$r" commit -q -m clean; then
  bad "(h) commit PASSED with a corrupt .gitleaks.toml (fail-open)" "$TMP/h.out"
elif grep -q 'scanner error' "$TMP/h.out"; then
  ok "(h) corrupt .gitleaks.toml blocked the commit as a scanner error"
else
  bad "(h) commit blocked for the wrong reason" "$TMP/h.out"
fi

# ── (i) worktree without the gate files is gated via the hook owner's copies ──
owner="$TMP/owner"
mkdir -p "$owner"
install_gate "$owner"
r="$TMP/i"
make_repo "$r" "$owner"
[ ! -f "$r/scripts/secret-scan.sh" ] && [ ! -f "$r/.gitleaks.toml" ] || bad "(i) setup: repo unexpectedly has gate files"
plant "$r"
if run "$TMP/i1.out" git -C "$r" commit -q -m leak; then
  bad "(i) planted credential COMMITTED in a repo relying on the hook owner's gate files" "$TMP/i1.out"
elif grep -q 'github-pat' "$TMP/i1.out"; then
  ok "(i) hook owner's secret-scan.sh + .gitleaks.toml gated a repo that has neither"
else
  bad "(i) commit blocked for the wrong reason" "$TMP/i1.out"
fi

# ── (j) redaction: the credential never appears in any transcript ─────────────
if grep -q "$PLANTED" "$ALL_OUT"; then
  bad "(j) the planted credential appeared in hook output"
else
  ok "(j) no transcript contains the planted credential ($(wc -l < "$ALL_OUT" | tr -d ' ') lines checked)"
fi

echo "test-secret-hooks: $PASS passed, $FAIL failed (gitleaks $(gitleaks version | tr -d '[:space:]'))"
[ "$FAIL" -eq 0 ]

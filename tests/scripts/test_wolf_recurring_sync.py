"""Unit tests for scripts/wolf_recurring_sync.py -- the CLAUDE.md recurring-bug digest.

The block is regenerated by a Stop hook after every turn and is also touched by
prettier (lint-staged). Both must agree on its layout byte for byte, or every
turn leaves CLAUDE.md dirty.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

from scripts import wolf_recurring_sync as sync

REPO_ROOT = Path(__file__).resolve().parents[2]
PRETTIER = REPO_ROOT / "node_modules" / ".bin" / "prettier"
IGNORE_START = "<!-- prettier-ignore-start -->"
IGNORE_END = "<!-- prettier-ignore-end -->"

BUG = {
    "id": "bug-001",
    "occurrences": 3,
    "last_seen": "2026-10-19T00:00:00Z",
    "error_message": "something broke",
    "fix": "fixed it",
    "tags": [],
}


def _run_sync(tmp_path, monkeypatch, claude_md_text: str, bugs: list[dict]) -> str:
    buglog = tmp_path / "buglog.json"
    buglog.write_text(json.dumps(bugs))
    claude_md = tmp_path / "CLAUDE.md"
    claude_md.write_text(claude_md_text)
    monkeypatch.setattr(sync, "BUGLOG", buglog)
    monkeypatch.setattr(sync, "CLAUDE_MD", claude_md)
    monkeypatch.setattr("sys.argv", ["wolf_recurring_sync.py"])
    assert sync.main() == 0
    return claude_md.read_text()


def _document(block: str) -> str:
    return f"# Title\n\nIntro.\n\n{IGNORE_START}\n\n{block}\n\n{IGNORE_END}\n"


def test_block_separates_markers_heading_and_list_with_blank_lines():
    block = sync.render_block([BUG])

    assert block.startswith(f"{sync.START}\n\n### Recurring issues")
    assert ")\n\n- **bug-001**" in block
    assert block.endswith(f"fixed it\n\n{sync.END}")


def test_empty_block_keeps_the_same_shape():
    block = sync.render_block([])

    assert block == (
        f"{sync.START}\n\n"
        "### Recurring issues (synced from `.wolf/buglog.json` — regenerate via "
        "`python scripts/wolf_recurring_sync.py`, do not hand-edit)\n\n"
        f"- none on record\n\n{sync.END}"
    )


def test_resync_is_a_no_op(tmp_path, monkeypatch):
    first = _run_sync(tmp_path, monkeypatch, _document(sync.render_block([])), [BUG])
    second = _run_sync(tmp_path, monkeypatch, first, [BUG])

    assert second == first


def test_claude_md_markers_sit_in_their_own_blocks():
    """Without blank lines, markdown merges the ignore and wolf markers into one
    HTML node and folds the end markers into the last list item, so prettier
    ignores the prettier-ignore range and rewrites the block."""
    text = (REPO_ROOT / "CLAUDE.md").read_text()

    assert f"{IGNORE_START}\n\n{sync.START}\n\n" in text
    assert f"\n\n{sync.END}\n\n{IGNORE_END}" in text


def test_synced_claude_md_layout_is_unchanged(tmp_path, monkeypatch):
    """Syncing the committed CLAUDE.md may update bug lines, never the layout."""
    committed = (REPO_ROOT / "CLAUDE.md").read_text()
    synced = _run_sync(tmp_path, monkeypatch, committed, [BUG])

    def outside_and_frame(text: str) -> tuple[str, str, str]:
        head, rest = text.split(sync.START, 1)
        _, tail = rest.split(sync.END, 1)
        frame = rest[: rest.index("\n- ")]
        return head, frame, tail

    assert outside_and_frame(synced) == outside_and_frame(committed)


@pytest.mark.skipif(
    not PRETTIER.exists() or shutil.which("node") is None,
    reason="prettier not installed (run npm install at the repo root)",
)
def test_prettier_leaves_synced_claude_md_unchanged(tmp_path, monkeypatch):
    long_bug = {**BUG, "error_message": "x " * 120, "fix": "y " * 120}
    committed = (REPO_ROOT / "CLAUDE.md").read_text()
    synced = _run_sync(tmp_path, monkeypatch, committed, [long_bug, BUG])

    # --stdin-filepath under the repo root, so the *.md override (80 columns,
    # proseWrap: always) applies exactly as it does to the real file.
    result = subprocess.run(
        [str(PRETTIER), "--stdin-filepath", str(REPO_ROOT / "CLAUDE.md")],
        input=synced,
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
        check=False,
    )

    assert result.returncode == 0, result.stderr
    assert result.stdout == synced
